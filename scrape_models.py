def calculate_quant_memory_gb(total_params_b, quant_key):
    """
    Calculate required memory in GB using Unsloth quantization ratios.
    """
    spec = UNSLOTH_QUANT_SPECS[quant_key]
    weight_bytes_gb = total_params_b * (spec["bits"] / 8.0) * 1.05
    kv_cache_gb = max(0.8, min(8.0, (total_params_b ** 0.5) * 0.32))
    runtime_overhead_gb = max(0.5, weight_bytes_gb * 0.035)
    total_required_gb = weight_bytes_gb + kv_cache_gb + runtime_overhead_gb
    return round(total_required_gb, 1)


def enrich_model(model):
    params = model["total_params_b"]
    model["memory_req_gb"] = {}
    model["quant_accuracy_pct"] = {}
    model["quant_ppl_delta"] = {}
    
    for qkey, qspec in UNSLOTH_QUANT_SPECS.items():
        model["memory_req_gb"][qkey] = calculate_quant_memory_gb(params, qkey)
        
        # Adjust accuracy retention for model size (larger models retain higher accuracy under quantization)
        size_bonus = 0.0
        if params >= 70.0:
            size_bonus = min(2.5, (params / 70.0) * 0.8)
        elif params <= 8.0:
            size_bonus = -max(1.0, (8.0 / params) * 0.9)
            
        model["quant_accuracy_pct"][qkey] = round(min(100.0, max(60.0, qspec["accuracy_pct"] + size_bonus)), 1)
        model["quant_ppl_delta"][qkey] = qspec["ppl_delta"]
        
    return model


